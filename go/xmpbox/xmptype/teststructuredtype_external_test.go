// stringGetter turns a typed accessor into the shape structuredRow wants, where
// the empty string is Java's null.
func stringGetter[T xmptype.AbstractStructuredType](read func(T) string) func(
	xmptype.AbstractStructuredType) (any, bool) {
	return func(s xmptype.AbstractStructuredType) (any, bool) {
		value := read(s.(T))
		return value, value != ""
	}
}

// stringSetter turns a typed setter into the shape structuredRow wants.
func stringSetter[T xmptype.AbstractStructuredType](write func(T, string) error) func(
	xmptype.AbstractStructuredType, any) error {
	return func(s xmptype.AbstractStructuredType, value any) error {
		return write(s.(T), value.(string))
	}
}

