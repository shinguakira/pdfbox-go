// structuredRow is one row of Java's initializeParameters, with the accessors
// its reflection would have found.
type structuredRow struct {
	// owner names the structured type, for the failure message.
	owner string

	// fieldName is the field being exercised.
	fieldName string

	// typeName is the Java class the stored property should have, which is
	// type.getImplementingClass().
	typeName string

	// value is the value to set, of the shape getJavaValue makes for the type.
	value any

	// make returns a fresh value of the structured type, with the names of
	// every field it declares.
	make func(m xmptype.MetadataLike) (xmptype.AbstractStructuredType, []string)

	// get reads the field back through the type's own accessor, and answers
	// false where the accessor says Java's null.
	get func(s xmptype.AbstractStructuredType) (any, bool)

	// set writes the field through the type's own accessor.
	set func(s xmptype.AbstractStructuredType, value any) error
}

