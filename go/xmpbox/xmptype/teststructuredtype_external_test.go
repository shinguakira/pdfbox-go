// TestStructuredInitializedToNull is Java's testInitializedToNull.
func TestStructuredInitializedToNull(t *testing.T) {
	xmp := xmpbox.CreateXMPMetadata()
	for _, row := range structuredRows() {
		structured, _ := row.make(xmp)
		if got := structured.Property(row.fieldName); got != nil {
			t.Errorf("%s.Property(%q) = %v on a fresh value, want nil",
				row.owner, row.fieldName, got)
		}
		// accessor
		if _, found := row.get(structured); found {
			t.Errorf("%s: the accessor of %q found a value on a fresh one, want none",
				row.owner, row.fieldName)
		}
	}
}

// TestStructuredSettingValue is Java's testSettingValue: setting one field
// leaves every other one the type declares unset.
func TestStructuredSettingValue(t *testing.T) {
	xmp := xmpbox.CreateXMPMetadata()
	for _, row := range structuredRows() {
		structured, fields := row.make(xmp)
		if err := row.set(structured, row.value); err != nil {
			t.Fatalf("%s.%s: %v", row.owner, row.fieldName, err)
		}
		if structured.Property(row.fieldName) == nil {
			t.Errorf("%s.Property(%q) = nil after it was set", row.owner, row.fieldName)
		}
		// check other properties not modified
		for _, name := range fields {
			// do not check the current name
			if name == row.fieldName {
				continue
			}
			if got := structured.Property(name); got != nil {
				t.Errorf("%s: setting %q also set %q to %v",
					row.owner, row.fieldName, name, got)
			}
		}
	}
}

// TestStructuredPropertyType is Java's testPropertyType: the stored property is
// of the class the Types constant names.
func TestStructuredPropertyType(t *testing.T) {
	xmp := xmpbox.CreateXMPMetadata()
	for _, row := range structuredRows() {
		structured, _ := row.make(xmp)
		if err := row.set(structured, row.value); err != nil {
			t.Fatalf("%s.%s: %v", row.owner, row.fieldName, err)
		}
		property := structured.Property(row.fieldName)
		if property == nil {
			t.Errorf("%s.Property(%q) = nil after it was set", row.owner, row.fieldName)
			continue
		}
		// check property type
		if got := property.TypeName(); got != row.typeName {
			t.Errorf("%s.%s is a %s, want a %s", row.owner, row.fieldName, got, row.typeName)
		}
	}
}

// TestStructuredSetter is Java's testSetter: the setter stores the value and
// the getter gives it back.
func TestStructuredSetter(t *testing.T) {
	xmp := xmpbox.CreateXMPMetadata()
	for _, row := range structuredRows() {
		structured, _ := row.make(xmp)
		if err := row.set(structured, row.value); err != nil {
			t.Fatalf("%s.%s: %v", row.owner, row.fieldName, err)
		}
		// check property set
		property, isSimple := structured.Property(row.fieldName).(xmptype.AbstractSimpleProperty)
		if !isSimple {
			t.Errorf("%s.%s is not a simple property", row.owner, row.fieldName)
			continue
		}
		if !sameValue(property.Value(), row.value) {
			t.Errorf("%s.%s stored %v, want %v",
				row.owner, row.fieldName, property.Value(), row.value)
		}
		// check getter
		got, found := row.get(structured)
		if !found {
			t.Errorf("%s: the accessor of %q found nothing after it was set",
				row.owner, row.fieldName)
			continue
		}
		if !sameValue(got, row.value) {
			t.Errorf("%s.%s reads back %v, want %v", row.owner, row.fieldName, got, row.value)
		}
	}
}

// sameValue is Java's assertEquals over the three shapes getJavaValue makes.
func sameValue(got, want any) bool {
	if wantTime, isTime := want.(time.Time); isTime {
		gotTime, isTime := got.(time.Time)
		return isTime && gotTime.Equal(wantTime)
	}
	return got == want
}
