// The bidirectional splitting of AbstractGlyphLayoutProcessor, against the
// running Java.
//
// java.text.Bidi has no Go equivalent -- golang.org/x/text/unicode/bidi runs the
// same algorithm but answers its runs in logical order and exposes no embedding
// level -- so go/javatext/bidi is UAX#9 written out, and this is what says it
// agrees with the JDK.
//
// Every wanted value below was printed by driving the running Java through
// AbstractGlyphLayoutProcessor.doBidiSplittingAndReordering by reflection. The
// corpus is in UTF-16 units rather than Go string literals, because the runs
// are UTF-16 substrings and one case carries a surrogate pair -- which Go
// refuses to write as a literal half at a time.

